int textWidth(const std::string& s) { return s.empty() ? 0 : static_cast<int>(s.size()) * GLYPH_ADVANCE - 1; }

int glyphIndex(char c) {
    int u = std::toupper(static_cast<unsigned char>(c));
    if (u < 32 || u > 127) u = '?';
    return u - 32;
}

Image makeFontAtlas() {
    Image img;
    img.w = FONT_COLS * FONT_CELL_W;
    img.h = FONT_ROWS * FONT_CELL_H;
    img.rgba.assign(static_cast<size_t>(img.w) * img.h * 4, 0);
    const Glyph* fallback = findGlyph('?');
    for (int code = 32; code < 128; ++code) {
        const Glyph* g = findGlyph(static_cast<char>(code));
        if (!g) g = fallback;
        int cell = code - 32;
        int ox = (cell % FONT_COLS) * FONT_CELL_W, oy = (cell / FONT_COLS) * FONT_CELL_H;
        for (int y = 0; y < GLYPH_H; ++y)
            for (int x = 0; x < GLYPH_W; ++x) {
                if (g->rows[y][x] != '#') continue;
                uint8_t* p = &img.rgba[(static_cast<size_t>(oy + y) * img.w + ox + x) * 4];
                p[0] = p[1] = p[2] = 255;
                p[3] = 191;  // tintable: text takes the colour it's drawn with
            }
    }
    return img;
}
